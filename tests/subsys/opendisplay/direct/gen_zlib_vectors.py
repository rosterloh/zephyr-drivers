"""Print src/zlib_vectors.inc: a 100x96 1 bpp image and its zlib streams.

Compressed as py-opendisplay 7.18.1 does it (level 6, 9-bit window).
"""

import random
import zlib

STRIDE, HEIGHT = 13, 96
rng = random.Random(82)
# Noise, then rows repeated from 18 rows (234 bytes) back: zlib's usable
# distance with a 512-byte window is 512 - 262.
rows = [bytes(rng.randrange(256) for _ in range(STRIDE)) for _ in range(60)]
for _ in range(HEIGHT - 60):
    rows.append(rows[-18])
image = b"".join(rows)


def deflate(wbits):
    c = zlib.compressobj(6, zlib.DEFLATED, wbits)
    return c.compress(image) + c.flush()


def emit(name, data):
    print(f"static const uint8_t {name}[] = {{")
    for i in range(0, len(data), 12):
        print("\t" + " ".join(f"0x{b:02x}," for b in data[i : i + 12]))
    print("};")


z9 = deflate(9)
assert zlib.decompress(z9) == image
print("/* Generated by gen_zlib_vectors.py. */")
emit("zimage", image)
emit("z9", z9)
emit("z15", deflate(15))
